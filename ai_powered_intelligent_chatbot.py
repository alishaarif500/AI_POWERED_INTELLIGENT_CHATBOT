"""## Phase 5: Conversational Memory Management

Conversational memory makes multi-turn interactions feel seamless. We will implement a memory manager that tracks history and includes a self-summarization utility when the history becomes too long.

### Short-term Memory vs. Long-term/Persistent Memory:
- **Short-term Memory (Context Window):** Exists inside the running session to let the model understand follow-up questions (e.g., "What did I just say?").
- **Persistent Memory (Vector DB/Databases):** Saves key facts permanently across multiple sessions (e.g., user preferences or database facts).
"""

class ConversationalMemory:
    def __init__(self, max_turns: int = 5):
        self.history = []  # List of dicts: {'role': 'user'|'model', 'text': str}
        self.max_turns = max_turns
        self.summary = ""

    def add_message(self, role: str, text: str):
        """Adds a dialogue turn to local short-term memory."""
        self.history.append({'role': role, 'text': text})

    def get_full_context_prompt(self, current_query: str) -> list:
        """
        Formats the history and current query into a structure suitable for the model API.
        Includes a running summary of previous history if it has been condensed.
        """
        formatted_contents = []

        # If we have a summary of older turns, provide it as context
        if self.summary:
            formatted_contents.append(
                f"System Background Summary of earlier conversation: {self.summary}\n"
            )

        # Append the active short-term history turns
        for turn in self.history:
            role_label = "User" if turn['role'] == 'user' else "Model"
            formatted_contents.append(f"{role_label}: {turn['text']}")

        # Finally, append current query
        formatted_contents.append(f"User: {current_query}")
        return "\n".join(formatted_contents)

    def reset(self):
        """Clears memory session entirely."""
        self.history = []
        self.summary = ""
        print("Conversational memory has been successfully reset!")

    def summarize_old_history(self, client, model_id='gemini-2.5-flash-lite'):
        """
        Triggers auto-summarization of history once active turns exceed threshold.
        This keeps token counts highly optimized.
        """
        if len(self.history) <= self.max_turns * 2:
            return

        print("\n[Memory System] Context limits reached. Summarizing conversation history...\n")

        # Extract history text to summarize
        history_text = "\n".join([f"{t['role']}: {t['text']}" for t in self.history])

        prompt = f"""Analyze the following conversation dialogue and write a concise,
factual paragraph summarizing the core discussion details, technical parameters discussed, or decisions made.

Dialogue:
{history_text}

Summary:"""
        try:
            response = client.models.generate_content(
                model=model_id,
                contents=prompt
            )
            self.summary = response.text.strip()
            # Keep only the last 2 turns in active history, the rest is now captured in summary!
            self.history = self.history[-2:]
        except Exception as e:
            print(f"Failed to summarize memory: {e}")

"""## Phase 6: Document Question Answering using RAG

In this phase, we build our core Retrieval-Augmented Generation (RAG) workflow. We implement a class `RAGAssistant` that processes uploaded PDF or TXT files, splits them into logical text chunks with overlaps to prevent contextual loss at boundaries, vectorizes them using a local embedding model, and indexes them using a FAISS database.
"""

import pymupdf  # Modern replacement for fitz
import faiss
import numpy as np
from sentence_transformers import SentenceTransformer

class RAGAssistant:
    def __init__(self, chunk_size: int = 500, chunk_overlap: int = 50):
        self.chunk_size = chunk_size
        self.chunk_overlap = chunk_overlap
        # Load a standard lightweight, high-performance semantic representation model
        self.embedder = SentenceTransformer('all-MiniLM-L6-v2')
        self.chunks = []
        self.index = None

    def extract_text_from_pdf(self, file_path: str) -> str:
        """Extracts raw text content page-by-page from an uploaded PDF."""
        text = ""
        try:
            doc = pymupdf.open(file_path)
            for page in doc:
                text += page.get_text() + "\n"
            return text
        except Exception as e:
            print(f"Error reading PDF: {e}")
            return ""

    def chunk_text(self, text: str):
        """
        Splits text into regular chunks of size self.chunk_size with overlap.
        Overlap preserves semantic continuity across chunk splits.
        """
        self.chunks = []
        words = text.split()
        i = 0
        while i < len(words):
            chunk_words = words[i:i + self.chunk_size]
            self.chunks.append(" ".join(chunk_words))
            i += self.chunk_size - self.chunk_overlap
        print(f"Successfully generated {len(self.chunks)} document chunks.")

    def build_vector_store(self):
        """
        Encodes chunks into semantic vector representations and constructs
        a local index using Facebook AI Similarity Search (FAISS).
        """
        if not self.chunks:
            print("No text chunks found. Please extract text and split chunks first.")
            return

        # 1. Compute Embeddings
        embeddings = self.embedder.encode(self.chunks, show_progress_bar=False)
        embeddings = np.array(embeddings).astype('float32')

        # 2. Setup Index
        dimension = embeddings.shape[1]
        self.index = faiss.IndexFlatL2(dimension)
        self.index.add(embeddings)
        print("FAISS vector store successfully constructed and indexed!")

    def retrieve_context(self, query: str, top_k: int = 3) -> list:
        """
        Performs semantic similarity search to fetch the most relevant text segments.
        """
        if self.index is None or not self.chunks:
            return []

        query_vector = self.embedder.encode([query]).astype('float32')
        distances, indices = self.index.search(query_vector, top_k)

        retrieved_contexts = []
        for idx in indices[0]:
            if idx != -1 and idx < len(self.chunks):
                retrieved_contexts.append(self.chunks[idx])
        return retrieved_contexts

    def get_grounded_rag_prompt(self, query: str, context_segments: list) -> str:
        """
        Builds a grounding system prompt that strictly forbids hallucination.
        """
        context_block = "\n---\n".join(context_segments)
        return f"""You are an expert academic research assistant.
Use ONLY the facts in the Context section below to answer the user's question.
If the context does not contain the answer, reply with: "I cannot find the answer in the provided documents."
Do not invent or assume any outside facts.

Context:
{context_block}

Question:
{query}

Answer:"""

"""## Phase 7: Local & LLM-Powered NLP Capabilities

This module implements a hybrid NLP engine. Local methods are utilized for high-speed preprocessing and statistical analysis, while Gemini handles semantic reasoning tasks like abstractive summarization.
"""

import re
from collections import Counter

class LocalNLPEngine:
    @staticmethod
    def clean_text(text: str) -> str:
        """Performs foundational text normalization and strips noise."""
        # Remove extra whitespace and special characters
        cleaned = re.sub(r'\s+', ' ', text)
        cleaned = re.sub(r'[^a-zA-Z0-9\s.\-,?!]', '', cleaned)
        return cleaned.strip()

    @staticmethod
    def extract_keywords(text: str, top_n: int = 5) -> list:
        """Extracts meaningful content words locally without calling external APIs."""
        stopwords = {
            'the', 'a', 'an', 'and', 'or', 'but', 'is', 'are', 'was', 'were',
            'of', 'at', 'by', 'for', 'with', 'about', 'to', 'in', 'on', 'this',
            'that', 'these', 'those', 'it', 'its', 'we', 'our', 'you', 'your'
        }
        words = re.findall(r'\b[a-zA-Z]{3,}\b', text.lower())
        content_words = [w for w in words if w not in stopwords]
        counter = Counter(content_words)
        return [item[0] for item in counter.most_common(top_n)]

    @staticmethod
    def get_abstractive_summary_prompt(text: str) -> str:
        """Formulates a structured prompt for LLM-based abstractive summarization."""
        return f"""You are an advanced text analysis system.
Generate a concise abstractive summary of the key findings in the text below.
Keep your summary structured with a 'Key Takeaway' followed by 3 bullet points.

Text:
{text}

Summary:"""

"""## Phase 8: System Evaluation & Latency Metrics

In this phase, we develop a benchmark utility class `SystemEvaluator`. This class computes performance statistics (average latency, recall rate, and context retrieval accuracy) to give you hard metrics to showcase in your portfolio's README or academic reports.
"""

import time

class SystemEvaluator:
    def __init__(self):
        self.latencies = []

    def measure_latency(self, func, *args, **kwargs):
        """Wraps execution to record precise response times."""
        start_time = time.perf_counter()
        result = func(*args, **kwargs)
        elapsed = time.perf_counter() - start_time
        self.latencies.append(elapsed)
        return result, elapsed

    def evaluate_retrieval(self, retriever_inst, test_queries: list, expected_keywords: list) -> dict:
        """
        Evaluates retrieval matching rate against a ground-truth set of semantic keywords.
        """
        successful_retrievals = 0
        total = len(test_queries)

        for query, expected_keyword in zip(test_queries, expected_keywords):
            contexts = retriever_inst.retrieve_context(query, top_k=2)
            combined_context = " ".join(contexts).lower()
            if expected_keyword.lower() in combined_context:
                successful_retrievals += 1

        recall_rate = (successful_retrievals / total) * 100 if total > 0 else 0.0
        return {
            "total_evaluated": total,
            "successful_hits": successful_retrievals,
            "recall_rate_percent": round(recall_rate, 2)
        }

